export function getSiteToothCrown(tooth: FDIToothNumber): SiteToothCrown {
  const crown = SITE_TOOTH_CROWNS[tooth];
  if (!crown) throw new Error(`No reverse-engineered crown path for tooth ${tooth}`);
  return crown;
}

export function getSiteCrownTransform(
  tooth: FDIToothNumber,
  targetWidth: number,
  targetHeight: number,
): string {
  const crown = getSiteToothCrown(tooth);
  const [x0, y0, x1, y1] = crown.bbox;
  const siteWidth = x1 - x0;
  const siteHeight = y1 - y0;
  const scaleX = targetWidth / siteWidth;
  const scaleY = targetHeight / siteHeight;
  const centerX = (x0 + x1) / 2;
  const cejY = crown.cej === 'top' ? y0 : y1;
  const flipY = crown.cej === 'top' ? 1 : -1;
  const tx = -centerX * scaleX;
  const ty = -cejY * scaleY * flipY;
  return `translate(${tx} ${ty}) scale(${scaleX} ${scaleY * flipY})`;
}

export function getSiteCrownPaths(tooth: FDIToothNumber): string[] {
  return Object.values(getSiteToothCrown(tooth).surfaces);
}

